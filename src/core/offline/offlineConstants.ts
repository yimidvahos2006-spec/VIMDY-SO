export const MAX_OFFLINE_ATTEMPTS = 5;
export const OFFLINE_BUSINESS_ERROR_PREFIXES = [
  "VALIDATION_ERROR",
  "INSUFFICIENT_STOCK",
  "PRODUCT_NOT_FOUND",
  "SALE_NOT_FOUND",
  "CATEGORY_NAME_DUPLICATE",
  "CATEGORY_IN_USE",
  "CATEGORY_NOT_FOUND",
  "CATEGORY_NAME_REQUIRED",
  "INVALID_AMOUNT",
  "PAYMENT_REFERENCE_REQUIRED",
  "INSUFFICIENT_PAYMENT",
  "SALE_LOCKED",
  "SALE_CANNOT_BE_CANCELLED",
  "SALE_NOT_PAID",
  "REFUND_NOTHING_LEFT",
  "PENDING_TABLE_OPERATION_MISSING_INPUT",
  "CONTEXT_MISMATCH",
  "NO_BUSINESS_CONTEXT",
  "ACCESS_DENIED",
  "ITEM_MISSING_ID",
  "ITEM_NOT_FOUND",
  "DUPLICATE_NAME",
  "COUNTRY_INVALID"
];

export function isBusinessError(error: unknown): boolean {
  const message = error instanceof Error ? error.message : String(error);
  return OFFLINE_BUSINESS_ERROR_PREFIXES.some((prefix) => message.startsWith(prefix));
}
